export default function FaqTabs() {
  const [active, setActive] = useState(0);
  return (
    <>
      <ul className="indexfaq-tablist js-tablist animation">
        {TABS.map((tab, i) => (
          <li
            key={tab.label}
            className={i === active ? "is-active" : ""}
            data-tab={i}
            onClick={() => setActive(i)}
          >
            {tab.label}
          </li>
        ))}
      </ul>
      <div className="indexfaq-content animation">
        {TABS.map((tab, i) => (
          <div
            key={tab.label}
            className={`indexfaq-block js-tabblock${i === active ? " is-active" : ""}`}
          >
            <dl className="indexfaq-block-list">
              {tab.faqs.map((faq) => (
                <FaqItem key={faq.q} faq={faq} />
              ))}
            </dl>
          </div>
        ))}
      </div>
    </>
  );
}

function FaqItem({ faq }: { faq: Faq }) {
  return (
    <>
      <dt>{faq.q}</dt>
      <dd>{faq.a}</dd>
    </>
  );
}
